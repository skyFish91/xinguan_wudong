/**
 * 按关键词匹配本地知识库
 * @returns 命中的答案，未命中返回 null
 */
export function matchFaq(input: string): string | null {
  const text = input.toLowerCase();
  let best: { score: number; answer: string } | null = null;

  for (const item of FAQ) {
    // 命中关键词越长越具体，用它做优先级，避免「票」这种短词抢答
    const hit = item.keywords
      .filter(k => text.includes(k.toLowerCase()))
      .sort((a, b) => b.length - a.length)[0];
    if (!hit) continue;
    if (!best || hit.length > best.score) {
      best = { score: hit.length, answer: item.answer };
    }
  }

  return best?.answer || null;
}
